	VEXTRACTF128 $1, y, X8; \
	VADDPS X8, x, x; \
	VMOVHLPS x, x, X8; \
	VADDPS X8, x, x; \
	VMOVSHDUP x, X8; \
	VADDSS X8, x, x; \
	MOVSS x, off(R9)


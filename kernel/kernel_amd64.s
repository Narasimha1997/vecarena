TEXT ·dotAVX2(SB), NOSPLIT, $0-28
	MOVQ a+0(FP), SI
	MOVQ b+8(FP), DI
	MOVQ n+16(FP), CX
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3

dot_loop32:
	CMPQ CX, $32
	JL   dot_loop8
	VMOVUPS (SI), Y4
	VMOVUPS 32(SI), Y5
	VMOVUPS 64(SI), Y6
	VMOVUPS 96(SI), Y7
	VFMADD231PS (DI), Y4, Y0
	VFMADD231PS 32(DI), Y5, Y1
	VFMADD231PS 64(DI), Y6, Y2
	VFMADD231PS 96(DI), Y7, Y3
	ADDQ $128, SI
	ADDQ $128, DI
	SUBQ $32, CX
	JMP  dot_loop32

dot_loop8:
	CMPQ CX, $8
	JL   dot_reduce
	VMOVUPS (SI), Y4
	VFMADD231PS (DI), Y4, Y0
	ADDQ $32, SI
	ADDQ $32, DI
	SUBQ $8, CX
	JMP  dot_loop8

dot_reduce:
	VADDPS Y1, Y0, Y0
	VADDPS Y3, Y2, Y2
	VADDPS Y2, Y0, Y0
	VEXTRACTF128 $1, Y0, X1
	VADDPS X1, X0, X0
	VMOVHLPS X0, X0, X1
	VADDPS X1, X0, X0
	VMOVSHDUP X0, X1
	VADDSS X1, X0, X0

dot_tail:
	TESTQ CX, CX
	JZ    dot_done
	VMOVSS (SI), X4
	VFMADD231SS (DI), X4, X0
	ADDQ $4, SI
	ADDQ $4, DI
	DECQ CX
	JMP  dot_tail

dot_done:
	VZEROUPPER
	MOVSS X0, ret+24(FP)
	RET

